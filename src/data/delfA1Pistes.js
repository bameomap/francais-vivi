export const PISTES = ROWS.map(([piste, kind, num, page]) => ({
  piste,
  label: `${kind === "A" ? "Activité" : "Exercice"} ${num}`,
  page,
  src: `/api/audio?b=delf-a1&p=${piste}`,
  section: SECTIONS.find(s => piste >= s.from && piste <= s.to),
}));

